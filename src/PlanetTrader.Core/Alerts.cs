namespace PlanetTrader.Core
{
    /// <summary>Какое важное событие: от этого зависит цвет и значок окна «Важное за ход».</summary>
    public enum AlertKind
    {
        /// <summary>Планету забрали: магнат через реестр или подкуп, коллекторы.</summary>
        PlanetLost,
        /// <summary>Угроза, на которую ещё можно ответить: подкуп жителей, иск в реестре.</summary>
        Threat,
        /// <summary>Пакость магнатов, которая бьёт сильно: картель, переманили менеджера или учёных. Слухи и заказчики — только в журнал.</summary>
        Trick,
        /// <summary>Беда на своей планете: бунт, забастовка. Метеориты (часты, страховка платит) — только в журнал.</summary>
        Disaster,
        /// <summary>Хорошее: угроза миновала, новый уровень корпорации.</summary>
        Good,
        /// <summary>Банкротство — партия окончена.</summary>
        Bankrupt,
        /// <summary>Шоу «Риелтор года» и «Лот недели»: новый сезон, задание выполнено, итоги, лот.</summary>
        Show,
    }

    /// <summary>
    /// Событие, которое серьёзно касается корпорации. Попадает и в журнал (как обычная строка), и в отчёт хода
    /// отдельно — интерфейс показывает такие окном, чтобы игрок их не пропустил.
    /// </summary>
    public sealed class Alert
    {
        public AlertKind Kind;
        /// <summary>Коротко, для заголовка: «Планету отсудили».</summary>
        public string Title;
        /// <summary>Подробно — та же строка, что в журнале.</summary>
        public string Text;
        /// <summary>О какой планете речь; −1 — ни о какой.</summary>
        public int PlanetId = -1;
        /// <summary>Какой магнат виноват; −1 — никакой.</summary>
        public int MagnateId = -1;
    }
}
